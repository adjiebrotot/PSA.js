"""Generate src/data/utm_usage.js: the USAGE blocks of pyproj's WKT for the UTM
zones on WGS 84 (EPSG 32601-32660, 32701-32760) and ETRS89 (25828-25838).

The rest of each WKT follows one template (src/core/crs.js), so only the
per-zone area descriptions are stored. test/fixtures/crs_utm_wkt.json.gz holds
pyproj's complete WKT strings to check the template against.

Usage: python scripts/generate_crs_data.py
"""

import gzip
import json
import re
from pathlib import Path

import pyproj

ROOT = Path(__file__).resolve().parent.parent
CODES = [*range(32601, 32661), *range(32701, 32761), *range(25828, 25839)]

usage = {}
wkts = {}
for code in CODES:
    wkt = pyproj.CRS.from_epsg(code).to_wkt()
    m = re.search(r",(USAGE\[.*\]),ID\[\"EPSG\",\d+\]\]$", wkt)
    usage[code] = m.group(1)
    wkts[code] = wkt

lines = [
    "// SPDX-License-Identifier: MIT",
    f"// Generated by scripts/generate_crs_data.py from pyproj {pyproj.__version__} (PROJ {pyproj.proj_version_str}); do not edit.",
    "/** USAGE blocks of the WKT of the UTM zones (EPSG code -> text). */",
    "export const UTM_USAGE = {",
    *[f"  {code}: {json.dumps(text, ensure_ascii=False)}," for code, text in usage.items()],
    "};",
    "",
]
(ROOT / "src" / "data" / "utm_usage.js").write_text("\n".join(lines), encoding="utf8")
with gzip.GzipFile(ROOT / "test" / "fixtures" / "crs_utm_wkt.json.gz", "wb", mtime=0) as f:
    f.write(json.dumps({"pyproj": pyproj.__version__, "proj": pyproj.proj_version_str, "wkt": wkts}, ensure_ascii=False, indent=0).encode())
print(f"wrote {len(usage)} zones")
