"""Generate src/data/definitions.js from the PyPSA source of truth.

Run with a Python environment where the reference PyPSA is installed:

    python scripts/generate_definitions.py

The component types are taken from ``pypsa.components.types`` *after* PyPSA
processed the CSV files, so defaults/dtypes are exactly what PyPSA uses.
"""

import json
import math
from pathlib import Path

import numpy as np
import pandas as pd
import pypsa
from pypsa.components.types import all_components, component_types_df

OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "definitions.js"


def to_json_value(v):
    if isinstance(v, (bool, np.bool_)):
        return bool(v)
    if isinstance(v, (int, np.integer)):
        return int(v)
    if isinstance(v, (float, np.floating)):
        f = float(v)
        if math.isnan(f):
            return {"$float": "nan"}
        if math.isinf(f):
            return {"$float": "inf" if f > 0 else "-inf"}
        return f
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None
    return str(v)


def frame_to_records(df: pd.DataFrame) -> dict:
    return {
        "index": [str(i) for i in df.index],
        "columns": list(df.columns),
        "data": {c: [to_json_value(x) for x in df[c]] for c in df.columns},
    }


components = []
for name in component_types_df.index:
    ct = None
    for c in all_components.values():
        if c.name == name:
            ct = c
    d = ct.defaults
    attrs = []
    for attr, row in d.iterrows():
        typ = row["typ"]
        typ_name = {bool: "bool", int: "int", str: "str", float: "float"}.get(typ, str(typ))
        attrs.append(
            {
                "attr": attr,
                "type": row["type"],
                "unit": None if pd.isna(row["unit"]) else str(row["unit"]),
                "default": to_json_value(row["default"]),
                "description": None if pd.isna(row["description"]) else str(row["description"]),
                "status": None if pd.isna(row["status"]) else str(row["status"]),
                "static": bool(row["static"]),
                "varying": bool(row["varying"]),
                "typ": typ_name,
                "dtype": str(row["dtype"]),
            }
        )
    st = None
    if ct.standard_types is not None:
        st = frame_to_records(ct.standard_types)
    components.append(
        {
            "name": ct.name,
            "list_name": ct.list_name,
            "description": ct.description,
            "category": None if pd.isna(ct.category) else str(ct.category),
            "attrs": attrs,
            "standard_types": st,
        }
    )

# piecewise attribute schema (x-axis attribute, auxiliary variable, extendable support)
piecewise = [
    {
        "component": str(row.component),
        "x": str(row.x),
        "y": str(row.y),
        "aux_variable": str(row.aux_variable),
        "allow_extendable": bool(row.allow_extendable),
    }
    for row in pd.read_csv(Path(pypsa.__file__).parent / "data" / "piecewise.csv").itertuples()
]

payload = {
    "pypsa_version": pypsa.__version__,
    "components": components,
    "piecewise": piecewise,
}
text = (
    "// AUTO-GENERATED by scripts/generate_definitions.py from PyPSA "
    f"({pypsa.__version__}). Do not edit by hand.\n"
    "// SPDX-License-Identifier: MIT (data derived from PyPSA, MIT licensed)\n"
    "export default "
    + json.dumps(payload, indent=1, ensure_ascii=False)
    + ";\n"
)
OUT.write_text(text)
print(f"Wrote {OUT} ({len(components)} components)")
